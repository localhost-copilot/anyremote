import AnyRemoteWire
import AppKit

/// Keeps this Mac's clipboard in step with the other Mac's, like Parallels'
/// shared clipboard: whatever is copied on one side can be pasted on the other.
///
/// Polls the general pasteboard (macOS has no change notification) and sends
/// new contents; applies what arrives. Text, rich text, HTML, images and URLs
/// are shared. Contents that password managers mark as concealed or
/// transient stay local, and so do copied files (they'd need a file transfer).
/// What was just applied isn't sent back, so two bridges on one pasteboard
/// (or a chain of Macs) don't ping-pong.
///
/// All pasteboard access happens on a queue of its own, never the main
/// thread. An app may only promise its data and hand it over when asked, and
/// Universal Clipboard fetches from another device on demand; until that
/// arrives a read blocks, and on the main thread that froze all of AnyRemote.
/// NSPasteboard can't move off the main thread: there is one object per
/// pasteboard, AppKit uses it on the main thread (validating Paste, for one),
/// and concurrent use crashed. So each bridge talks to the clipboard through
/// a Pasteboard Manager reference of its own, used only on its queue.
@MainActor
public final class PasteboardBridge {
    public nonisolated static let maximumBytes = 16 << 20

    nonisolated static let sharedTypes: [NSPasteboard.PasteboardType] = [
        .string, .rtf, .html, .png, .URL, .init("public.jpeg"), .init("public.url-name"), .init("com.apple.flat-rtfd"),
    ]
    nonisolated static let privateMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]

    private let worker: Worker

    public init(pasteboard: NSPasteboard = .general, send: @escaping @Sendable ([PasteboardItem]) -> Void) {
        worker = Worker(pasteboard: pasteboard, send: send)
    }

    /// `sendingCurrent` also sends what's on the clipboard now.
    public func start(sendingCurrent: Bool) { worker.start(sendingCurrent: sendingCurrent) }

    public func stop() { worker.stop() }

    public func apply(_ items: [PasteboardItem]) { worker.apply(items) }

    /// Looks for a change now and waits for it to be sent (tests).
    func poll() { worker.queue.sync { worker.poll() } }

    /// Waits until everything asked of the bridge so far is done (tests).
    func waitUntilIdle() { worker.queue.sync {} }

    private final class Worker: @unchecked Sendable {
        let queue = DispatchQueue(label: "com.localhost-copilot.anyremote.pasteboard", qos: .utility)
        private let send: @Sendable ([PasteboardItem]) -> Void
        // Queue-confined.
        private let board: ClipboardReference?
        private var forceRead = false
        private var last: [PasteboardItem]?
        private var timer: DispatchSourceTimer?

        init(pasteboard: NSPasteboard, send: @escaping @Sendable ([PasteboardItem]) -> Void) {
            self.send = send
            board = ClipboardReference(name: pasteboard.name)
            // What's on the clipboard already isn't a new copy.
            queue.async { [board] in _ = board?.synchronize() }
        }

        func start(sendingCurrent: Bool) {
            queue.async { [self] in
                if sendingCurrent { forceRead = true }
                timer?.cancel()
                let timer = DispatchSource.makeTimerSource(queue: queue)
                timer.schedule(deadline: .now(), repeating: .milliseconds(500), leeway: .milliseconds(100))
                timer.setEventHandler { [weak self] in self?.poll() }
                timer.resume()
                self.timer = timer
            }
        }

        func stop() {
            queue.async { [self] in
                timer?.cancel()
                timer = nil
            }
        }

        func poll() {
            guard let board else { return }
            let changed = board.synchronize()
            guard changed || forceRead else { return }
            forceRead = false
            guard let items = PasteboardBridge.read(board), items != last else { return }
            last = items
            send(items)
        }

        func apply(_ items: [PasteboardItem]) {
            queue.async { [self] in
                guard let board, !items.isEmpty, items != last else { return }
                last = items
                board.write(items)
                // Our own write isn't a copy to send back.
                _ = board.synchronize()
            }
        }
    }

    nonisolated static func read(_ board: ClipboardReference) -> [PasteboardItem]? {
        let items = board.items()
        let all = Set(items.flatMap(\.flavors))
        guard all.isDisjoint(with: privateMarkers), !all.contains(NSPasteboard.PasteboardType.fileURL.rawValue)
        else { return nil }
        var total = 0
        var result: [PasteboardItem] = []
        for item in items {
            var types: [String: Data] = [:]
            for type in sharedTypes where item.flavors.contains(type.rawValue) {
                if let data = board.data(item, type.rawValue) { types[type.rawValue] = data }
            }
            // Screenshots and many apps offer only TIFF, which is large; send PNG.
            let tiff = NSPasteboard.PasteboardType.tiff.rawValue
            if types[NSPasteboard.PasteboardType.png.rawValue] == nil, types["public.jpeg"] == nil,
               item.flavors.contains(tiff), let data = board.data(item, tiff),
               let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]) {
                types[NSPasteboard.PasteboardType.png.rawValue] = png
            }
            guard !types.isEmpty else { continue }
            total += types.values.reduce(0) { $0 + $1.count }
            result.append(PasteboardItem(types: types))
        }
        guard !result.isEmpty, total <= maximumBytes else { return nil }
        return result
    }
}

/// A Pasteboard Manager reference to a pasteboard: independent of AppKit's
/// NSPasteboard object, so it can be used off the main thread. Not
/// thread-safe itself; each bridge confines its own to its queue.
final class ClipboardReference: @unchecked Sendable {
    struct Item {
        let id: PasteboardItemID
        let flavors: [String]
    }

    private let reference: Pasteboard

    init?(name: NSPasteboard.Name) {
        let cfName = (name == .general ? kPasteboardClipboard : name.rawValue) as CFString
        var reference: Pasteboard?
        guard PasteboardCreate(cfName, &reference) == noErr, let reference else { return nil }
        self.reference = reference
    }

    /// Catches up with the pasteboard; true when it changed since last time.
    func synchronize() -> Bool {
        PasteboardSynchronize(reference).contains(.modified)
    }

    func items() -> [Item] {
        var count = 0
        guard PasteboardGetItemCount(reference, &count) == noErr, count > 0 else { return [] }
        return (1...count).compactMap { index in
            var id: PasteboardItemID?
            var flavors: CFArray?
            guard PasteboardGetItemIdentifier(reference, index, &id) == noErr, let id,
                  PasteboardCopyItemFlavors(reference, id, &flavors) == noErr else { return nil }
            return Item(id: id, flavors: (flavors as? [String]) ?? [])
        }
    }

    func data(_ item: Item, _ flavor: String) -> Data? {
        var data: CFData?
        guard PasteboardCopyItemFlavorData(reference, item.id, flavor as CFString, &data) == noErr else { return nil }
        return data as Data?
    }

    func write(_ items: [PasteboardItem]) {
        guard PasteboardClear(reference) == noErr else { return }
        _ = PasteboardSynchronize(reference)
        for (index, item) in items.enumerated() {
            // Item IDs only need to be distinct, non-zero values.
            guard let id = PasteboardItemID(bitPattern: index + 1) else { continue }
            for (flavor, data) in item.types {
                PasteboardPutItemFlavor(reference, id, flavor as CFString, data as CFData, [])
            }
        }
    }
}
