import AnyRemoteWire
import AppKit
import CryptoKit
import OSLog

private let log = Logger(subsystem: "com.localhost-copilot.anyremote", category: "Clipboard")

/// Keeps this Mac's clipboard in step with the other Macs', like Parallels'
/// shared clipboard: whatever is copied on one can be pasted on another.
///
/// One per process: every connection that shares the clipboard joins it as
/// a `Peer`, so a copy is read once however many Macs are connected, and
/// what one Mac sent is passed on to the others. macOS has no change
/// notification, so it polls the pasteboard while anyone has joined.
///
/// A copy goes out as a `PasteboardOffer`: short text inline, every other
/// type by name and digest only. Text, rich text, HTML, images and URLs are
/// shared. Contents that password managers mark as concealed or transient
/// stay local, and so do copied files (dragging them copies them).
///
/// What arrives is written at once, its inline types as data and the rest
/// as promises: a type crosses the network only when an app here pastes
/// it, over the transfer connection so it never holds up input. A copy is
/// still read in full here when it's made: comparing contents is what
/// stops one coming back (Universal Clipboard syncs AnyRemote's write
/// between a user's Macs, and a viewer of this Mac shares this pasteboard),
/// and the digests let the other side compare without fetching. An offer
/// also carries where it was copied first, so one relayed around a ring of
/// connections is dropped.
///
/// All pasteboard access happens on `ClipboardReference.queue`, never the
/// main thread: an app may only promise its data and hand it over when
/// asked, and Universal Clipboard fetches from another device on demand;
/// until that arrives a read blocks. macOS asks for our own promises on the
/// main thread, which then waits for the fetch (see `keepPromise`).
public final class SharedClipboard: @unchecked Sendable {
    /// The clipboard, or for tests on one Mac a pasteboard of this name
    /// (`ANYREMOTE_PASTEBOARD`), so a host and a viewer each have their own.
    public static let shared = SharedClipboard(
        pasteboard: ProcessInfo.processInfo.environment["ANYREMOTE_PASTEBOARD"].map { .init($0) } ?? .general)

    /// Fetches one type of an offer from the Mac that made it; `reply` (any
    /// thread) takes nil when it's unavailable.
    public typealias Fetcher = @Sendable (_ offerID: UInt32, _ item: Int, _ type: String,
                                          _ reply: @escaping @Sendable (Data?) -> Void) -> Void

    static let sharedTypes: [NSPasteboard.PasteboardType] = [
        .string, .rtf, .html, .png, .URL, .init("public.jpeg"), .init("public.url-name"), .init("com.apple.flat-rtfd"),
    ]
    /// Types sent inline, within `inlineBytes`: what pasting text needs.
    static let inlineTypes: Set<String> = [
        NSPasteboard.PasteboardType.string.rawValue, NSPasteboard.PasteboardType.URL.rawValue, "public.url-name",
    ]
    /// Image types in order of preference.
    static let imageTypes = [NSPasteboard.PasteboardType.png.rawValue, "public.jpeg"]
    static let privateMarkers: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword", "de.petermaurer.TransientPasteboardType",
    ]
    /// Inline data per offer, at most: text this short pastes without a fetch.
    static let inlineBytes = 64 << 10
    /// A type larger than this is not shared; the item's other types still are.
    static let maximumBytes = PasteboardOffer.maximumTypeBytes
    /// How long an app pasting here waits for a type from the other Mac.
    static let promiseTimeout: TimeInterval = 15

    /// A connection sharing the clipboard. Thread-safe.
    public final class Peer: @unchecked Sendable {
        fileprivate weak var clipboard: SharedClipboard?
        fileprivate let send: @Sendable (PasteboardOffer) -> Void
        fileprivate let fetch: Fetcher

        fileprivate init(clipboard: SharedClipboard, send: @escaping @Sendable (PasteboardOffer) -> Void,
                         fetch: @escaping Fetcher) {
            self.clipboard = clipboard
            self.send = send
            self.fetch = fetch
        }

        /// The other Mac's clipboard changed.
        public func receive(_ offer: PasteboardOffer) { clipboard?.receive(offer, from: self) }

        /// The other Mac asks for one type of what this Mac offered it.
        public func provide(offerID: UInt32, item: Int, type: String, reply: @escaping @Sendable (Data?) -> Void) {
            guard let clipboard else { return reply(nil) }
            clipboard.provide(offerID: offerID, item: item, type: type, reply: reply)
        }

        public func leave() { clipboard?.leave(self) }
    }

    var queue: DispatchQueue { ClipboardReference.queue }
    /// This launch, as the origin of its copies.
    let origin = UUID()
    /// A copy made here, all read already, for fetches served without the
    /// queue: it may be busy reading this pasteboard, and what it reads may
    /// be another process's promise waiting on that very fetch (a viewer of
    /// this Mac shares its pasteboard).
    private let localLock = NSLock()
    private var local: (offerID: UInt32, items: [[String: Data]])? // under localLock
    // Queue-confined.
    private let board: ClipboardReference?
    private var peers: [Peer] = []
    private var timer: DispatchSourceTimer?
    /// What the clipboard holds, as offered to peers.
    private var current: Content? {
        didSet {
            let local = current.flatMap { content in
                content.source == nil && content.origin == origin
                    ? (content.offerID, content.items.map { $0.offered.inline.merging($0.cache) { old, _ in old } })
                    : nil
            }
            localLock.withLock { self.local = local }
        }
    }
    /// What this clipboard last wrote to the pasteboard, while it's still there.
    /// The pasteboard is never read back then: its promised types would
    /// ask this process, on the main thread, for data this queue waits for.
    private var written: Content?
    private var keepsPromises = false
    private var copies: UInt32 = 0
    private var nextOfferID: UInt32 = 0

    init(pasteboard: NSPasteboard.Name) {
        board = ClipboardReference(name: pasteboard)
    }

    /// Starts sharing with one more connection. `sendingCurrent` also
    /// offers it what's on the clipboard now. `send` and `fetch` are called
    /// on the clipboard's queue.
    public func join(sendingCurrent: Bool, send: @escaping @Sendable (PasteboardOffer) -> Void,
                     fetch: @escaping Fetcher) -> Peer {
        let peer = Peer(clipboard: self, send: send, fetch: fetch)
        queue.async { [self] in
            if peers.isEmpty { start() }
            peers.append(peer)
            guard sendingCurrent else { return }
            if current == nil, written == nil, let board {
                _ = board.synchronize()
                if let items = Self.read(board) { current = makeLocal(items) }
            }
            if let current, current.source !== peer { peer.send(current.offer) }
        }
        return peer
    }

    /// Looks for a copy now (tests).
    func pollNow() { queue.sync { poll() } }

    /// Waits until everything asked of the clipboard so far is done (tests).
    func waitUntilIdle() { queue.sync {} }

    private func leave(_ peer: Peer) {
        queue.async { [self] in
            peers.removeAll { $0 === peer }
            guard peers.isEmpty else { return }
            timer?.cancel()
            timer = nil
            // Nobody can fetch it any more; promises still on the pasteboard now fail at once.
            current = nil
            written = nil
        }
    }

    private func start() {
        if !keepsPromises, let board {
            keepsPromises = true
            board.keepPromises { [weak self] item, type in
                self?.keepPromise(item: item, type: type) ?? OSStatus(badPasteboardFlavorErr)
            }
        }
        // What's on the clipboard already isn't a new copy.
        _ = board?.synchronize()
        current = nil
        let timer = DispatchSource.makeTimerSource(queue: queue)
        timer.schedule(deadline: .now() + .milliseconds(500), repeating: .milliseconds(500), leeway: .milliseconds(100))
        timer.setEventHandler { [weak self] in self?.poll() }
        timer.resume()
        self.timer = timer
    }

    // MARK: Copies made here

    func poll() {
        dispatchPrecondition(condition: .onQueue(queue))
        guard let board, board.synchronize() else { return }
        written = nil
        guard let items = Self.read(board) else {
            // Something private, or nothing to share: earlier offers end.
            current = nil
            return
        }
        if let current, current.signature == items.map(\.offered) {
            // The same contents again: what was written here coming back. Keep
            // what was read, so a peer's fetch needn't go to the other Mac.
            for (index, item) in items.enumerated() { current.items[index].cache.merge(item.cache) { old, _ in old } }
            return
        }
        let content = makeLocal(items)
        current = content
        broadcast(content, except: nil)
    }

    private func makeLocal(_ items: [Content.Item]) -> Content {
        copies &+= 1
        return Content(offerID: makeOfferID(), origin: origin, copy: copies, items: items, source: nil,
                       sourceOfferID: 0)
    }

    /// The pasteboard's shareable contents: per item, the inline data, and
    /// the digest and data of every other type. Nil for something private
    /// or nothing shareable.
    static func read(_ board: ClipboardReference) -> [Content.Item]? {
        let items = board.items()
        let all = Set(items.flatMap(\.flavors))
        guard all.isDisjoint(with: privateMarkers), !all.contains(NSPasteboard.PasteboardType.fileURL.rawValue)
        else { return nil }
        var inlineUsed = 0
        var result: [Content.Item] = []
        for item in items {
            var entry = Content.Item()
            func fetched(_ type: String, _ data: Data) {
                entry.offered.fetched[type] = Data(SHA256.hash(data: data))
                entry.cache[type] = data
            }
            // One image type is enough (the system adds PNG and JPEG to TIFF by itself).
            let image = imageTypes.first { item.flavors.contains($0) }
            for type in sharedTypes.map(\.rawValue) where item.flavors.contains(type) {
                if imageTypes.contains(type), type != image { continue }
                guard let data = board.data(item, type), data.count <= maximumBytes else { continue }
                if inlineTypes.contains(type), inlineUsed + data.count <= inlineBytes {
                    inlineUsed += data.count
                    entry.offered.inline[type] = data
                } else {
                    fetched(type, data)
                }
            }
            // Screenshots and many apps offer only TIFF, which is large; send PNG.
            let tiff = NSPasteboard.PasteboardType.tiff.rawValue
            if image == nil, item.flavors.contains(tiff), let data = board.data(item, tiff),
               let png = NSBitmapImageRep(data: data)?.representation(using: .png, properties: [:]),
               png.count <= maximumBytes {
                fetched(NSPasteboard.PasteboardType.png.rawValue, png)
            }
            guard !entry.offered.inline.isEmpty || !entry.offered.fetched.isEmpty else { continue }
            result.append(entry)
        }
        return result.isEmpty ? nil : result
    }

    // MARK: Copies made elsewhere

    private func receive(_ offer: PasteboardOffer, from peer: Peer) {
        queue.async { [self] in
            guard peers.contains(where: { $0 === peer }), !offer.items.isEmpty else { return }
            // Our own copy came back, or this one arrived another way first.
            if offer.origin == origin { return }
            if let current, current.origin == offer.origin, current.copy >= offer.copy { return }
            if let current, current.signature == offer.items { return }
            let content = Content(offerID: makeOfferID(), origin: offer.origin, copy: offer.copy,
                                  items: offer.items.map { Content.Item(offered: $0) },
                                  source: peer, sourceOfferID: offer.offerID)
            current = content
            broadcast(content, except: peer)
            guard let board else { return }
            board.write(content.items.map { ($0.offered.inline, Array($0.offered.fetched.keys)) })
            // Our own write isn't a copy to send back.
            _ = board.synchronize()
            written = content
        }
    }

    /// An app here pastes a type the other Mac offered: fetches it and puts
    /// it on the pasteboard. macOS calls this on the main thread, and the
    /// pasting app waits meanwhile, so it gives up after `promiseTimeout`.
    private func keepPromise(item: PasteboardItemID, type: String) -> OSStatus {
        let failed = OSStatus(badPasteboardFlavorErr)
        // Only a read on our own queue could ask from there, and that queue is the one that would answer.
        guard !ClipboardReference.isOnQueue else { return failed }
        let index = Int(bitPattern: item) - 1
        let arrived = DispatchSemaphore(value: 0)
        let result = PromiseResult()
        queue.async { [self] in
            guard let content = written, content.items.indices.contains(index) else {
                arrived.signal()
                return
            }
            result.content = content
            load(content, item: index, type: type) { data in
                result.data = data
                arrived.signal()
            }
        }
        let started = Date()
        guard arrived.wait(timeout: .now() + Self.promiseTimeout) == .success, let data = result.data else {
            log.error("could not fetch \(type, privacy: .public) for a paste")
            return failed
        }
        let waited = Int(Date().timeIntervalSince(started) * 1000)
        log.notice("fetched \(type, privacy: .public) for a paste: \(data.count) bytes in \(waited) ms")
        return queue.sync {
            // Replaced meanwhile: the pasteboard no longer holds this promise.
            guard written === result.content, let board else { return failed }
            let status = board.fulfill(item: item, type: type, data: data)
            // Handing it over isn't a copy either.
            _ = board.synchronize()
            return status
        }
    }

    // MARK: Serving fetches

    private func provide(offerID: UInt32, item: Int, type: String, reply: @escaping @Sendable (Data?) -> Void) {
        if let local = localLock.withLock({ local }), local.offerID == offerID {
            return reply(local.items.indices.contains(item) ? local.items[item][type] : nil)
        }
        queue.async { [self] in
            guard let current, current.offerID == offerID, current.items.indices.contains(item) else {
                return reply(nil)
            }
            if let data = current.items[item].offered.inline[type] { return reply(data) }
            load(current, item: item, type: type, reply: reply)
        }
    }

    /// One type of an item, from the cache or else from the Mac it was copied
    /// on; fetches of the same type wait for one another.
    private func load(_ content: Content, item: Int, type: String, reply: @escaping @Sendable (Data?) -> Void) {
        dispatchPrecondition(condition: .onQueue(queue))
        guard let digest = content.items[item].offered.fetched[type] else { return reply(nil) }
        if let data = content.items[item].cache[type] { return reply(data) }
        let key = Content.Key(item: item, type: type)
        if content.waiting[key] != nil {
            content.waiting[key]?.append(reply)
            return
        }
        guard let source = content.source else { return reply(nil) }
        content.waiting[key] = [reply]
        source.fetch(content.sourceOfferID, item, type) { [self] data in
            queue.async {
                // Not what was offered: the other Mac's clipboard changed meanwhile.
                let data = data.flatMap { Data(SHA256.hash(data: $0)) == digest ? $0 : nil }
                if let data { content.items[item].cache[type] = data }
                for waiter in content.waiting.removeValue(forKey: key) ?? [] { waiter(data) }
            }
        }
    }

    // MARK: -

    private func broadcast(_ content: Content, except excluded: Peer?) {
        let offer = content.offer
        for peer in peers where peer !== excluded { peer.send(offer) }
    }

    private func makeOfferID() -> UInt32 {
        nextOfferID &+= 1
        return nextOfferID
    }

    /// What a paste waits for, filled on the clipboard's queue before the semaphore is signalled.
    private final class PromiseResult: @unchecked Sendable {
        var content: Content?
        var data: Data?
    }

    /// What the clipboard holds, as offered to peers. Confined to the clipboard's queue.
    final class Content: @unchecked Sendable {
        struct Item {
            var offered = PasteboardOfferItem()
            /// Data of fetched types, once read or fetched.
            var cache: [String: Data] = [:]
        }

        struct Key: Hashable {
            let item: Int
            let type: String
        }

        let offerID: UInt32
        let origin: UUID
        let copy: UInt32
        var items: [Item]
        /// The peer it came from; nil for a copy made on this Mac (or once
        /// that peer is gone).
        weak var source: Peer?
        let sourceOfferID: UInt32
        var waiting: [Key: [@Sendable (Data?) -> Void]] = [:]

        init(offerID: UInt32, origin: UUID, copy: UInt32, items: [Item], source: Peer?, sourceOfferID: UInt32) {
            self.offerID = offerID
            self.origin = origin
            self.copy = copy
            self.items = items
            self.source = source
            self.sourceOfferID = sourceOfferID
        }

        /// Tells one copy's contents from another's.
        var signature: [PasteboardOfferItem] { items.map(\.offered) }

        var offer: PasteboardOffer {
            PasteboardOffer(offerID: offerID, origin: origin, copy: copy, items: signature)
        }
    }
}

/// A Pasteboard Manager reference to a pasteboard: independent of AppKit's
/// NSPasteboard object, so it can be used off the main thread.
///
/// Every reference must be used only on `queue`. Separate references are not
/// independent: the Pasteboard Manager keeps per-pasteboard lookup caches
/// shared by all of a process's references, unguarded, and a host session's
/// bridge reading the clipboard while the viewer's bridge did crashed
/// AnyRemote in `GetPerPasteboardLookupCollections`.
public final class ClipboardReference: @unchecked Sendable {
    /// The one queue for all Pasteboard Manager use in this process. Drags
    /// are read here too, so it runs at their priority.
    public static let queue: DispatchQueue = {
        let queue = DispatchQueue(label: "com.localhost-copilot.anyremote.pasteboard", qos: .userInitiated)
        queue.setSpecific(key: queueKey, value: ())
        return queue
    }()
    private static let queueKey = DispatchSpecificKey<Void>()

    static var isOnQueue: Bool { DispatchQueue.getSpecific(key: queueKey) != nil }

    public struct Item {
        let id: PasteboardItemID
        public let flavors: [String]
    }

    /// Answers for promised types. Called by macOS on the main thread.
    typealias PromiseKeeper = @Sendable (_ item: PasteboardItemID, _ type: String) -> OSStatus

    private final class KeeperBox {
        let keep: PromiseKeeper
        init(_ keep: @escaping PromiseKeeper) { self.keep = keep }
    }

    private let reference: Pasteboard
    private var keeper: KeeperBox?

    public init?(name: NSPasteboard.Name) {
        let cfName = (name == .general ? kPasteboardClipboard : name.rawValue) as CFString
        var reference: Pasteboard?
        guard PasteboardCreate(cfName, &reference) == noErr, let reference else { return nil }
        self.reference = reference
    }

    /// Catches up with the pasteboard; true when it changed since last time.
    public func synchronize() -> Bool {
        PasteboardSynchronize(reference).contains(.modified)
    }

    public func items() -> [Item] {
        var count = 0
        guard PasteboardGetItemCount(reference, &count) == noErr, count > 0 else { return [] }
        return (1...count).compactMap { index in
            var id: PasteboardItemID?
            var flavors: CFArray?
            guard PasteboardGetItemIdentifier(reference, index, &id) == noErr, let id,
                  PasteboardCopyItemFlavors(reference, id, &flavors) == noErr else { return nil }
            return Item(id: id, flavors: (flavors as? [String]) ?? [])
        }
    }

    public func data(_ item: Item, _ flavor: String) -> Data? {
        var data: CFData?
        guard PasteboardCopyItemFlavorData(reference, item.id, flavor as CFString, &data) == noErr else { return nil }
        return data as Data?
    }

    /// Lets `write` promise types; set once, before the first promise.
    func keepPromises(_ keep: @escaping PromiseKeeper) {
        let box = KeeperBox(keep)
        keeper = box
        PasteboardSetPromiseKeeper(reference, { _, item, flavor, context in
            guard let context else { return OSStatus(badPasteboardFlavorErr) }
            return Unmanaged<KeeperBox>.fromOpaque(context).takeUnretainedValue().keep(item, flavor as String)
        }, Unmanaged.passUnretained(box).toOpaque())
    }

    /// Replaces the contents: per item, its data, and the types promised
    /// (nil data) for the keeper to provide when asked.
    func write(_ items: [(data: [String: Data], promised: [String])]) {
        guard PasteboardClear(reference) == noErr else { return }
        _ = PasteboardSynchronize(reference)
        for (index, item) in items.enumerated() {
            // Item IDs only need to be distinct, non-zero values.
            guard let id = PasteboardItemID(bitPattern: index + 1) else { continue }
            for (flavor, data) in item.data {
                PasteboardPutItemFlavor(reference, id, flavor as CFString, data as CFData, [])
            }
            for flavor in item.promised where keeper != nil {
                PasteboardPutItemFlavor(reference, id, flavor as CFString, nil, [])
            }
        }
    }

    /// Hands over a promised type.
    func fulfill(item: PasteboardItemID, type: String, data: Data) -> OSStatus {
        PasteboardPutItemFlavor(reference, item, type as CFString, data as CFData, [])
    }
}
